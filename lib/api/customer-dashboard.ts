type CancelBookingResponse = {
  message: string;
  bookingId: string;
  status: "cancelled";
};

export async function cancelCustomerBooking(bookingId: string): Promise<CancelBookingResponse> {
  
// const token = await getTokenFromServer();
  const response = await fetch(
    `${API_BASE_URL}/customer/bookings/${encodeURIComponent(bookingId)}/cancel`,
    {
      method: "PATCH",
      headers: {
        Accept: "application/json",
        // Authorization: `Bearer ${token}`,
      },
    }
  );

  const result = (await response.json()) as {
    message?: string;
    bookingId?: string;
    status?: "cancelled";
  };

  if (!response.ok) {
    throw new Error(
      result.message || "Unable to cancel this booking."
    );
  }

  return result as CancelBookingResponse;
};





// Get all bookings belonging to the logged-in customer
export async function getCustomerBookings(customerEmail: string): Promise<CustomerBooking[]> {
  if (!customerEmail) {
    throw new Error("Customer email is required.");
  }

  // Get Better Auth JWT
  const token = await getTokenFromClient();

  const response = await fetch(
    `${API_BASE_URL}/customer/all-bookings/${encodeURIComponent(customerEmail)}`,
    {
      method: "GET",
      headers: {
        Accept: "application/json",
        Authorization: `Bearer ${token}`,
      },
      cache: "no-store",
    }
  );
  const result = await response.json();

  if (!response.ok) {
    throw new Error(
      result.message || "Unable to fetch your bookings."
    );
  }

  if (!Array.isArray(result)) {
    throw new Error("Invalid bookings response from server.");
  }

  return result as CustomerBooking[];
}






// Create Stripe Checkout Session
type CreateCheckoutSessionResponse = {
  message: string;
  url: string;
  sessionId: string;
};

export async function createCustomerCheckoutSession(bookingId: string): Promise<CreateCheckoutSessionResponse> {
  if (!bookingId) {
    throw new Error("Booking ID is required.");
  }

  // Retrieve the JWT generated by Better Auth.
  const { data, error } = await authClient.token();

  if (error || !data?.token) {
    throw new Error(
      error?.message || "Unable to authenticate your payment request."
    );
  }

  const response = await fetch(`${API_BASE_URL}/api/payments/create-checkout-session`,
    {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Accept: "application/json",
        Authorization: `Bearer ${data.token}`,
      },
      body: JSON.stringify({bookingId}),
      cache: "no-store",
    }
  );

  const result = await response.json();

  if (!response.ok) {
    throw new Error(
      result.message || "Unable to create checkout session."
    );
  }

  if (!result.url || !result.sessionId) {
    throw new Error("Invalid response from the payment server.");
  }

  return result as CreateCheckoutSessionResponse;
}